/**
 * Index coverage report (CLAUDE.md §8): every Mongoose query call site in backend/src, and the
 * `expectIndexedQuery()` test that proves it uses an index. Static, reads files only.
 *   pnpm --filter @zuvo/backend index:coverage           # writes docs/runbooks/index-coverage.md
 *   pnpm --filter @zuvo/backend index:coverage --check   # also exits 1 if there is a gap
 */
import { globSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { buildReport, type Notes, renderReport } from '../db/index-coverage.ts';

const backend = join(import.meta.dirname, '..', '..');
const output = join(backend, '..', 'docs', 'runbooks', 'index-coverage.md');

/** Sites the scanner cannot judge, checked by hand. Key: `file:method:enclosing declaration`. */
const NOTES: Notes = {
  'src/chats/sync.service.ts:find:syncSince':
    '`{ $or: [{ chatId, seq: { $in } }, …] }` built with `.map()`: each branch on `{ chatId, seq }`, tested in `src/chats/chat-indexes.test.ts` ("sync")',
};

const read = (pattern: string) =>
  globSync(pattern, { cwd: backend })
    .map((file) => file.replaceAll('\\', '/'))
    .sort()
    .map((file) => ({ file, text: readFileSync(join(backend, file), 'utf8') }));

const isTest = (file: string) => file.endsWith('.test.ts');
const sources = read('src/**/*.ts').filter(
  ({ file }) => !isTest(file) && !file.startsWith('src/scripts/'),
);
const tests = read('src/**/*.test.ts');
const report = buildReport(sources, tests, NOTES);

const header = [
  '# Index coverage',
  '',
  'Generated by `pnpm --filter @zuvo/backend index:coverage` (`backend/src/scripts/index-coverage.ts`).',
  'Do not edit by hand: change the code or the tests and run it again.',
  '',
  'Every Mongoose query call site in `backend/src` (tests and `src/scripts/` excluded), matched to an',
  '`expectIndexedQuery()` test (CLAUDE.md §8) by **model + filter fields**. A test of a subset of a',
  "site's fields covers it too: extra predicates never take an index away. `$or.x` = a field inside",
  '`$or`/`$and`; `fn:name` = a filter built by `name()`; `…` = fields the scanner cannot see.',
  '',
  'It is a static, text-based scan: it can miss a call written in an unusual way, and a shape match',
  'does not prove the operators match (e.g. a partial index needs the same `$type`/`$exists`). The',
  'tests themselves run `explain()` and are the real check.',
  '',
];
writeFileSync(output, `${header.join('\n')}${renderReport(report)}`);
const { counts } = report;
process.stdout.write(
  `${relative(process.cwd(), output)}: ${counts.total} sites, ${counts.covered} covered by a test, ${counts.id} by _id, ${counts.review} reviewed, ${counts.gap} gaps\n`,
);
if (process.argv.includes('--check') && counts.gap > 0) process.exit(1);
