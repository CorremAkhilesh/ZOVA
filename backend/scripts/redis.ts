/**
 * Local Redis for Zuvo: a separate Memurai process run as the current user (no Windows service,
 * no admin rights). Config and data live in backend/storage/redis/ (gitignored).
 *
 *   node scripts/redis.ts start | stop | status
 *
 * Port and password come from REDIS_URL in backend/.env. The shared Memurai service on port 6379
 * belongs to other projects and is never touched.
 */
import { spawn } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { setTimeout as sleep } from 'node:timers/promises';
import { fileURLToPath } from 'node:url';
import { parseEnv } from 'node:util';
import { Redis } from 'ioredis';
import { withStartLock } from './start-lock.ts';

const MEMURAI_EXE = 'C:\\Program Files\\Memurai\\memurai.exe';
const SHARED_PORT = 6379;
const START_TIMEOUT_MS = 15_000;

// ZUVO_REDIS_HOME: another folder, to try this script beside a Redis that is already running.
const root =
  process.env.ZUVO_REDIS_HOME ?? fileURLToPath(new URL('../storage/redis/', import.meta.url));
const dataDir = `${root}data`;
const confPath = `${root}memurai.conf`;
const logPath = `${root}memurai.log`;
const lockPath = `${root}start.lock`;

const out = (line: string) => process.stdout.write(`[redis] ${line}\n`);

function fail(message: string): never {
  process.stderr.write(`[redis] ${message}\n`);
  process.exit(1);
}

interface Target {
  port: number;
  password: string;
}

function readTarget(): Target | null {
  const envFile = fileURLToPath(new URL('../.env', import.meta.url));
  const fileEnv = existsSync(envFile) ? parseEnv(readFileSync(envFile, 'utf8')) : {};
  const raw = process.env.REDIS_URL ?? fileEnv.REDIS_URL ?? '';
  if (raw === '') return null;

  const url = new URL(raw);
  if (url.hostname !== '127.0.0.1' && url.hostname !== 'localhost') return null;
  const port = Number(url.port || 6379);
  if (port === SHARED_PORT) {
    fail(`REDIS_URL points at port ${SHARED_PORT}, the shared Memurai service. Use 6391.`);
  }
  const password = decodeURIComponent(url.password);
  if (password === '')
    fail('REDIS_URL must include a password (redis://:<password>@127.0.0.1:6391)');
  return { port, password };
}

/** Forward slashes keep Windows paths valid inside the Memurai config. */
const confPathValue = (path: string) => `"${path.replaceAll('\\', '/')}"`;

function writeConfig({ port, password }: Target) {
  mkdirSync(dataDir, { recursive: true });
  const lines = [
    '# GENERATED by backend/scripts/redis.ts from REDIS_URL. Do not edit; do not commit.',
    'bind 127.0.0.1',
    'protected-mode yes',
    `port ${port}`,
    `requirepass ${password}`,
    '# BullMQ requires noeviction: queue keys must never be evicted.',
    'maxmemory 256mb',
    'maxmemory-policy noeviction',
    'appendonly yes',
    'appendfsync everysec',
    'save 3600 1 300 100 60 10000',
    'dbfilename dump.rdb',
    `dir ${confPathValue(dataDir)}`,
    `logfile ${confPathValue(logPath)}`,
    'loglevel notice',
  ];
  writeFileSync(confPath, `${lines.join('\n')}\n`);
}

type Probe = 'ours' | 'foreign' | 'down';

/** Is our instance answering on the port, is something else there, or is it free? */
async function probe({ port, password }: Target): Promise<Probe> {
  const client = new Redis({
    host: '127.0.0.1',
    port,
    password,
    lazyConnect: true,
    connectTimeout: 1000,
    maxRetriesPerRequest: 0,
    retryStrategy: () => null,
  });
  client.on('error', () => {});
  try {
    await client.connect();
    return (await client.ping()) === 'PONG' ? 'ours' : 'foreign';
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    return /ECONNREFUSED|ETIMEDOUT|Connection is closed/.test(message) ? 'down' : 'foreign';
  } finally {
    client.disconnect();
  }
}

async function withClient<T>(
  { port, password }: Target,
  run: (c: Redis) => Promise<T>,
): Promise<T> {
  const client = new Redis({ host: '127.0.0.1', port, password, maxRetriesPerRequest: 1 });
  // SHUTDOWN drops the connection on purpose.
  client.on('error', () => {});
  try {
    return await run(client);
  } finally {
    client.disconnect();
  }
}

async function launch(target: Target) {
  // Someone else may have started it while we waited for the lock.
  const state = await probe(target);
  if (state === 'ours') return out(`already running on 127.0.0.1:${target.port}`);
  if (state === 'foreign')
    fail(`port ${target.port} is used by something else. Pick another port in REDIS_URL.`);
  if (!existsSync(MEMURAI_EXE)) fail(`Memurai not found at ${MEMURAI_EXE}`);

  writeConfig(target);
  const child = spawn(MEMURAI_EXE, [confPath], {
    detached: true,
    stdio: 'ignore',
    windowsHide: true,
  });
  child.unref();

  const deadline = Date.now() + START_TIMEOUT_MS;
  while (Date.now() < deadline) {
    if ((await probe(target)) === 'ours') {
      return out(`started on 127.0.0.1:${target.port} (pid ${child.pid}); data in ${dataDir}`);
    }
    await sleep(300);
  }
  fail(`did not start within ${START_TIMEOUT_MS / 1000}s; see ${logPath}`);
}

async function start(target: Target) {
  if ((await probe(target)) === 'ours') return out(`already running on 127.0.0.1:${target.port}`);
  mkdirSync(root, { recursive: true });
  // Parallel calls take turns, so at most one of them ever launches Memurai.
  await withStartLock(lockPath, () => launch(target));
}

async function stop(target: Target) {
  if ((await probe(target)) !== 'ours') return out(`not running on 127.0.0.1:${target.port}`);
  // SHUTDOWN saves the data and exits; the connection drops, so the error is expected.
  await withClient(target, (c) => c.call('SHUTDOWN').catch(() => undefined));
  for (let i = 0; i < 30; i++) {
    if ((await probe(target)) === 'down') return out('stopped');
    await sleep(200);
  }
  fail('still running after SHUTDOWN');
}

async function status(target: Target) {
  const state = await probe(target);
  if (state !== 'ours') {
    out(
      state === 'down'
        ? `stopped (port ${target.port} free)`
        : `port ${target.port} is used by something else`,
    );
    process.exitCode = state === 'down' ? 3 : 1;
    return;
  }
  const details = await withClient(target, async (c) => {
    const info = await c.info('server');
    const field = (name: string) =>
      new RegExp(`^${name}:(.*)$`, 'm').exec(info)?.[1]?.trim() ?? '?';
    const policy = (await c.config('GET', 'maxmemory-policy')) as string[];
    return `pid ${field('process_id')}, uptime ${field('uptime_in_seconds')}s, policy ${policy[1]}`;
  });
  out(`running on 127.0.0.1:${target.port} (${details})`);
}

async function main() {
  const command = process.argv[2];
  if (!['start', 'stop', 'status'].includes(command ?? ''))
    fail('usage: redis.ts start|stop|status');

  if (process.platform !== 'win32') {
    return out('not on Windows: run Redis yourself (CI and the VPS use a Redis container)');
  }
  const target = readTarget();
  if (!target) {
    return out('REDIS_URL is empty or not local: nothing to manage (the API runs without Redis)');
  }
  if (command === 'start') await start(target);
  else if (command === 'stop') await stop(target);
  else await status(target);
}

await main();
