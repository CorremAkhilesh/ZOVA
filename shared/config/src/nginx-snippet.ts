import { appSecurityHeaders } from './security-headers.ts';

/** Where `pnpm security:nginx` writes the snippet, relative to the repository root. */
export const NGINX_SNIPPET_PATH = 'infra/nginx/security-headers.conf';

/** Nginx double-quoted strings: escape backslashes and quotes (our values contain neither today). */
const quoted = (value: string) => `"${value.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;

/**
 * The production app headers as Nginx `add_header … always;` lines. `always` also covers error
 * pages (404, 5xx). Generated from security-headers.ts: never edit the .conf by hand.
 */
export function nginxSecurityHeaders(): string {
  const lines = Object.entries(appSecurityHeaders({ production: true })).map(
    ([name, value]) => `add_header ${name} ${quoted(value)} always;`,
  );
  return [
    '# GENERATED by `pnpm security:nginx` from shared/config/src/security-headers.ts. Do not edit.',
    '# Include inside every Nginx location that serves the web app (not /v1 or /socket.io:',
    '# the API sets its own headers). See infra/nginx/README.md.',
    ...lines,
    '',
  ].join('\n');
}
